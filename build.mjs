import { readFile, writeFile } from 'node:fs/promises';
const base=new URL('./',import.meta.url);
const read=p=>readFile(new URL(p,base),'utf8');
let html=await read('index.html');
const css=await read('src/style.css');
let js='';
for(const path of ['src/core.js','src/render.js','src/app.js'])js+='\n'+(await read(path)).replace(/^import .*?;\s*$/gm,'').replace(/^export /gm,'');
html=html.replace('<link rel="stylesheet" href="/src/style.css">',`<style>${css}</style>`).replace('<script type="module" src="/src/app.js"></script>',`<script type="module">\n${js.replaceAll('</script','<\\/script')}\n</script>`);
await writeFile(new URL('play.html',base),html);
console.log(`Built standalone play.html (${Math.round(Buffer.byteLength(html)/1024)} KiB). No network or installation needed.`);
